/**
 * 監看 Host 的暫停／提示鈕：Host 把被打開的覆蓋層記在 [tw.dynity.wrongbutton.core.engine.LocalHostEvents]。
 */
@Composable
fun HostButtonsWatcher(onPause: () -> Unit, onHint: () -> Unit) {
    val events = tw.dynity.wrongbutton.core.engine.LocalHostEvents.current
    LaunchedEffect(events) {
        events.collect { e ->
            when (e) {
                tw.dynity.wrongbutton.core.engine.HostOverlay.Pause -> onPause()
                tw.dynity.wrongbutton.core.engine.HostOverlay.Hints -> onHint()
                else -> Unit
            }
        }
    }
}
